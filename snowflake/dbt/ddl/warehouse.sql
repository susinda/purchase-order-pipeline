CREATE TABLE IF NOT EXISTS PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER (
    ORDER_NUMBER VARCHAR NOT NULL PRIMARY KEY,
    ORDER_TYPE VARCHAR,
    ORDER_STATUS VARCHAR,
    CREATION_TIME TIMESTAMP_TZ,
    LAST_UPDATED TIMESTAMP_TZ,
    SUPPLIER_CODE VARCHAR,
    SUPPLIER_NAME VARCHAR,
    CREATOR VARCHAR,
    PURCHASE_CURRENCY VARCHAR,
    NET_SUM NUMBER(18,2),
    TAX_SUM NUMBER(18,2),
    GROSS_SUM NUMBER(18,2),
    SOURCE_EVENT_ID VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE (
    ORDER_NUMBER VARCHAR NOT NULL,
    LINE_NUMBER VARCHAR NOT NULL,
    LINE_KEY VARCHAR NOT NULL,
    LINE_STATUS VARCHAR,
    DESCRIPTION VARCHAR,
    CATEGORY_CODE VARCHAR,
    CATEGORY_NAME VARCHAR,
    QUANTITY VARCHAR,
    QUANTITY_UNIT VARCHAR,
    NET_UNIT_PRICE NUMBER(18,2),
    NET_SUM NUMBER(18,2),
    TAX_CODE VARCHAR,
    TAX_PERCENT NUMBER(18,3),
    TAX_TOTAL NUMBER(18,2),
    GROSS_SUM NUMBER(18,2),
    DESIRED_DELIVERY_DATE DATE,
    PRIMARY KEY (ORDER_NUMBER, LINE_NUMBER),
    FOREIGN KEY (ORDER_NUMBER) REFERENCES PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER (ORDER_NUMBER)
);

CREATE TABLE IF NOT EXISTS PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE_CODING_ROW (
    ORDER_NUMBER VARCHAR NOT NULL,
    LINE_NUMBER VARCHAR NOT NULL,
    ROW_INDEX VARCHAR NOT NULL,
    CODING_KEY VARCHAR NOT NULL,
    SPLIT_PERCENT NUMBER(18,3),
    ACCOUNT_CODE VARCHAR,
    ACCOUNT_NAME VARCHAR,
    COST_CENTER_CODE VARCHAR,
    COST_CENTER_NAME VARCHAR,
    PROJECT_CODE VARCHAR,
    PRIMARY KEY (ORDER_NUMBER, LINE_NUMBER, ROW_INDEX),
    FOREIGN KEY (ORDER_NUMBER, LINE_NUMBER)
        REFERENCES PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE (ORDER_NUMBER, LINE_NUMBER)
);

CREATE TABLE IF NOT EXISTS PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE_GOODS_RECEIPT (
    GOODS_RECEIPT_NUMBER VARCHAR NOT NULL PRIMARY KEY,
    ORDER_NUMBER VARCHAR NOT NULL,
    LINE_NUMBER VARCHAR NOT NULL,
    REVERSED_GOODS_RECEIPT_NUMBER VARCHAR,
    RECEIVING_DATE DATE,
    RECEIVED_QUANTITY NUMBER(18,3),
    RECEIVED_NET_SUM NUMBER(18,2),
    RECIPIENT VARCHAR,
    FOREIGN KEY (ORDER_NUMBER, LINE_NUMBER)
        REFERENCES PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE (ORDER_NUMBER, LINE_NUMBER),
    FOREIGN KEY (REVERSED_GOODS_RECEIPT_NUMBER)
        REFERENCES PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE_GOODS_RECEIPT (GOODS_RECEIPT_NUMBER)
);

CREATE TABLE IF NOT EXISTS PURCHASE_ORDER_DB.BIZ.DIM_SUPPLIER (
    SUPPLIER_CODE VARCHAR NOT NULL PRIMARY KEY,
    SUPPLIER_NAME VARCHAR
);

CREATE TABLE IF NOT EXISTS PURCHASE_ORDER_DB.BIZ.DIM_PURCHASE_ORDER (
    ORDER_NUMBER VARCHAR NOT NULL PRIMARY KEY,
    ORDER_STATUS VARCHAR,
    ORDER_TYPE VARCHAR,
    CREATION_TIME TIMESTAMP_TZ,
    LAST_UPDATED TIMESTAMP_TZ,
    SUPPLIER_CODE VARCHAR,
    PURCHASE_CURRENCY VARCHAR,
    NET_SUM NUMBER(18,2),
    TAX_SUM NUMBER(18,2),
    GROSS_SUM NUMBER(18,2)
);

CREATE TABLE IF NOT EXISTS PURCHASE_ORDER_DB.BIZ.FACT_PURCHASE_ORDER_LINE (
    LINE_KEY VARCHAR NOT NULL PRIMARY KEY,
    ORDER_NUMBER VARCHAR NOT NULL,
    LINE_NUMBER VARCHAR NOT NULL,
    SUPPLIER_CODE VARCHAR,
    PURCHASE_CURRENCY VARCHAR,
    LINE_STATUS VARCHAR,
    CATEGORY_CODE VARCHAR,
    QUANTITY NUMBER(18,3),
    QUANTITY_UNIT VARCHAR,
    NET_SUM NUMBER(18,2),
    TAX_TOTAL NUMBER(18,2),
    GROSS_SUM NUMBER(18,2),
    DESIRED_DELIVERY_DATE DATE
);

CREATE TABLE IF NOT EXISTS PURCHASE_ORDER_DB.BIZ.FACT_GOODS_RECEIPT (
    GOODS_RECEIPT_NUMBER VARCHAR NOT NULL PRIMARY KEY,
    ORDER_NUMBER VARCHAR NOT NULL,
    LINE_NUMBER VARCHAR NOT NULL,
    SUPPLIER_CODE VARCHAR,
    REVERSED_GOODS_RECEIPT_NUMBER VARCHAR,
    RECEIVING_DATE DATE,
    RECEIVED_QUANTITY NUMBER(18,3),
    RECEIVED_NET_SUM NUMBER(18,2)
);

CREATE OR REPLACE SECURE VIEW PURCHASE_ORDER_DB.BIZ.VW_PURCHASE_ORDERS COPY GRANTS AS
SELECT o.ORDER_NUMBER, o.ORDER_STATUS, o.ORDER_TYPE, o.CREATION_TIME, o.LAST_UPDATED,
       o.SUPPLIER_CODE, s.SUPPLIER_NAME, o.PURCHASE_CURRENCY, o.NET_SUM, o.TAX_SUM, o.GROSS_SUM
FROM PURCHASE_ORDER_DB.BIZ.DIM_PURCHASE_ORDER o
LEFT JOIN PURCHASE_ORDER_DB.BIZ.DIM_SUPPLIER s ON s.SUPPLIER_CODE = o.SUPPLIER_CODE;

CREATE OR REPLACE SECURE VIEW PURCHASE_ORDER_DB.BIZ.VW_PURCHASE_ORDER_LINES COPY GRANTS AS
SELECT l.LINE_KEY, l.ORDER_NUMBER, l.LINE_NUMBER, l.SUPPLIER_CODE, s.SUPPLIER_NAME,
       l.PURCHASE_CURRENCY, l.LINE_STATUS, l.CATEGORY_CODE, l.QUANTITY, l.QUANTITY_UNIT,
       l.NET_SUM, l.TAX_TOTAL, l.GROSS_SUM, l.DESIRED_DELIVERY_DATE
FROM PURCHASE_ORDER_DB.BIZ.FACT_PURCHASE_ORDER_LINE l
LEFT JOIN PURCHASE_ORDER_DB.BIZ.DIM_SUPPLIER s ON s.SUPPLIER_CODE = l.SUPPLIER_CODE;

CREATE OR REPLACE SECURE VIEW PURCHASE_ORDER_DB.BIZ.VW_GOODS_RECEIPTS COPY GRANTS AS
SELECT r.GOODS_RECEIPT_NUMBER, r.ORDER_NUMBER, r.LINE_NUMBER, r.SUPPLIER_CODE, s.SUPPLIER_NAME,
       o.PURCHASE_CURRENCY, r.REVERSED_GOODS_RECEIPT_NUMBER, r.RECEIVING_DATE,
       r.RECEIVED_QUANTITY, r.RECEIVED_NET_SUM
FROM PURCHASE_ORDER_DB.BIZ.FACT_GOODS_RECEIPT r
LEFT JOIN PURCHASE_ORDER_DB.BIZ.DIM_SUPPLIER s ON s.SUPPLIER_CODE = r.SUPPLIER_CODE
LEFT JOIN PURCHASE_ORDER_DB.BIZ.DIM_PURCHASE_ORDER o ON o.ORDER_NUMBER = r.ORDER_NUMBER;

CREATE OR REPLACE SECURE VIEW PURCHASE_ORDER_DB.BIZ.VW_CODING_ALLOCATIONS COPY GRANTS AS
SELECT ORDER_NUMBER, LINE_NUMBER, ROW_INDEX, CODING_KEY, SPLIT_PERCENT,
       ACCOUNT_CODE, ACCOUNT_NAME, COST_CENTER_CODE, COST_CENTER_NAME, PROJECT_CODE
FROM PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE_CODING_ROW;
