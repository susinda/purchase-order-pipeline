CREATE OR REPLACE SECURE VIEW PURCHASE_ORDER_DB.BIZ.VW_PURCHASE_ORDERS COPY GRANTS AS
SELECT o.ORDER_NUMBER, o.ORDER_STATUS, o.ORDER_TYPE, o.CREATION_TIME, o.LAST_UPDATED,
       o.SUPPLIER_CODE, s.SUPPLIER_NAME, o.PURCHASE_CURRENCY, o.NET_SUM, o.TAX_SUM, o.GROSS_SUM
FROM PURCHASE_ORDER_DB.BIZ.DIM_PURCHASE_ORDER o
LEFT JOIN PURCHASE_ORDER_DB.BIZ.DIM_SUPPLIER s ON s.SUPPLIER_CODE = o.SUPPLIER_CODE;

CREATE OR REPLACE SECURE VIEW PURCHASE_ORDER_DB.BIZ.VW_PURCHASE_ORDER_LINES COPY GRANTS AS
SELECT l.LINE_KEY, l.ORDER_NUMBER, l.LINE_NUMBER, l.SUPPLIER_CODE, s.SUPPLIER_NAME,
       l.PURCHASE_CURRENCY, l.LINE_STATUS, l.CATEGORY_CODE, l.QUANTITY, l.QUANTITY_UNIT,
       l.NET_SUM, l.TAX_TOTAL, l.GROSS_SUM, l.DESIRED_DELIVERY_DATE
FROM PURCHASE_ORDER_DB.BIZ.FACT_PURCHASE_ORDER_LINE l
LEFT JOIN PURCHASE_ORDER_DB.BIZ.DIM_SUPPLIER s ON s.SUPPLIER_CODE = l.SUPPLIER_CODE;

CREATE OR REPLACE SECURE VIEW PURCHASE_ORDER_DB.BIZ.VW_GOODS_RECEIPTS COPY GRANTS AS
SELECT r.GOODS_RECEIPT_NUMBER, r.ORDER_NUMBER, r.LINE_NUMBER, r.SUPPLIER_CODE, s.SUPPLIER_NAME,
       o.PURCHASE_CURRENCY, r.REVERSED_GOODS_RECEIPT_NUMBER, r.RECEIVING_DATE,
       r.RECEIVED_QUANTITY, r.RECEIVED_NET_SUM
FROM PURCHASE_ORDER_DB.BIZ.FACT_GOODS_RECEIPT r
LEFT JOIN PURCHASE_ORDER_DB.BIZ.DIM_SUPPLIER s ON s.SUPPLIER_CODE = r.SUPPLIER_CODE
LEFT JOIN PURCHASE_ORDER_DB.BIZ.DIM_PURCHASE_ORDER o ON o.ORDER_NUMBER = r.ORDER_NUMBER;

CREATE OR REPLACE SECURE VIEW PURCHASE_ORDER_DB.BIZ.VW_CODING_ALLOCATIONS COPY GRANTS AS
SELECT ORDER_NUMBER, LINE_NUMBER, ROW_INDEX, CODING_KEY, SPLIT_PERCENT,
       ACCOUNT_CODE, ACCOUNT_NAME, COST_CENTER_CODE, COST_CENTER_NAME, PROJECT_CODE
FROM PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE_CODING_ROW;
