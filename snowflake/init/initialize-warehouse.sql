CREATE TABLE IF NOT EXISTS <% raw_table %> (
    EVENT_ID VARCHAR NOT NULL PRIMARY KEY,
    BATCH_ID VARCHAR NOT NULL,
    ORDER_NUMBER VARCHAR NOT NULL,
    LOAD_TYPE VARCHAR,
    PAYLOAD VARIANT NOT NULL,
    INGESTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

EXECUTE IMMEDIATE $$
DECLARE
    compatible_columns INTEGER;
    required_extra_columns INTEGER;
    ingested_at_columns INTEGER;
    incompatible_ingested_at INTEGER;
    incompatible_table EXCEPTION (-20001,
        'The RAW table does not match the ingestion schema. Use a compatible SNOWFLAKE_RAW_TABLE or migrate the existing table.');
BEGIN
    SELECT
        COUNT_IF((COLUMN_NAME = 'PAYLOAD' AND DATA_TYPE = 'VARIANT') OR
            (COLUMN_NAME IN ('EVENT_ID', 'BATCH_ID', 'ORDER_NUMBER', 'LOAD_TYPE')
                AND DATA_TYPE IN ('TEXT', 'VARCHAR')
                AND (COLUMN_NAME <> 'LOAD_TYPE' OR IS_NULLABLE = 'YES'))),
        COUNT_IF(COLUMN_NAME NOT IN ('EVENT_ID', 'BATCH_ID', 'ORDER_NUMBER', 'LOAD_TYPE', 'PAYLOAD')
            AND COLUMN_NAME <> 'INGESTED_AT' AND IS_NULLABLE = 'NO'
            AND COLUMN_DEFAULT IS NULL AND IS_IDENTITY = 'NO'),
        COUNT_IF(COLUMN_NAME = 'INGESTED_AT'),
        COUNT_IF(COLUMN_NAME = 'INGESTED_AT' AND DATA_TYPE <> 'TIMESTAMP_LTZ')
    INTO :compatible_columns, :required_extra_columns, :ingested_at_columns, :incompatible_ingested_at
    FROM <% database %>.INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA = UPPER(SPLIT_PART('<% raw_table %>', '.', 2))
        AND TABLE_NAME = UPPER(SPLIT_PART('<% raw_table %>', '.', 3));

    IF (COALESCE(compatible_columns, 0) <> 5 OR COALESCE(required_extra_columns, 0) > 0
        OR COALESCE(incompatible_ingested_at, 0) > 0) THEN
        RAISE incompatible_table;
    END IF;
    IF (COALESCE(ingested_at_columns, 0) = 0) THEN
        ALTER TABLE <% raw_table %> ADD COLUMN IF NOT EXISTS INGESTED_AT TIMESTAMP_LTZ;
    END IF;
    RETURN 'Purchase-order RAW table is ready';
END;
$$;

CREATE TABLE IF NOT EXISTS PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER (
    ORDER_NUMBER VARCHAR NOT NULL PRIMARY KEY,
    ORDER_TYPE VARCHAR,
    ORDER_STATUS VARCHAR,
    CREATION_TIME TIMESTAMP_TZ,
    LAST_UPDATED TIMESTAMP_TZ,
    SUPPLIER_CODE VARCHAR,
    SUPPLIER_NAME VARCHAR,
    CREATOR VARCHAR,
    PURCHASE_CURRENCY VARCHAR,
    NET_SUM NUMBER(18,2),
    TAX_SUM NUMBER(18,2),
    GROSS_SUM NUMBER(18,2),
    SOURCE_EVENT_ID VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE (
    ORDER_NUMBER VARCHAR NOT NULL,
    LINE_NUMBER VARCHAR NOT NULL,
    LINE_KEY VARCHAR NOT NULL,
    LINE_STATUS VARCHAR,
    DESCRIPTION VARCHAR,
    CATEGORY_CODE VARCHAR,
    CATEGORY_NAME VARCHAR,
    QUANTITY VARCHAR,
    QUANTITY_UNIT VARCHAR,
    NET_UNIT_PRICE NUMBER(18,2),
    NET_SUM NUMBER(18,2),
    TAX_CODE VARCHAR,
    TAX_PERCENT NUMBER(18,3),
    TAX_TOTAL NUMBER(18,2),
    GROSS_SUM NUMBER(18,2),
    DESIRED_DELIVERY_DATE DATE,
    PRIMARY KEY (ORDER_NUMBER, LINE_NUMBER),
    FOREIGN KEY (ORDER_NUMBER) REFERENCES PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER (ORDER_NUMBER)
);

CREATE TABLE IF NOT EXISTS PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE_CODING_ROW (
    ORDER_NUMBER VARCHAR NOT NULL,
    LINE_NUMBER VARCHAR NOT NULL,
    ROW_INDEX VARCHAR NOT NULL,
    CODING_KEY VARCHAR NOT NULL,
    SPLIT_PERCENT NUMBER(18,3),
    ACCOUNT_CODE VARCHAR,
    ACCOUNT_NAME VARCHAR,
    COST_CENTER_CODE VARCHAR,
    COST_CENTER_NAME VARCHAR,
    PROJECT_CODE VARCHAR,
    PRIMARY KEY (ORDER_NUMBER, LINE_NUMBER, ROW_INDEX),
    FOREIGN KEY (ORDER_NUMBER, LINE_NUMBER)
        REFERENCES PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE (ORDER_NUMBER, LINE_NUMBER)
);

CREATE TABLE IF NOT EXISTS PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE_GOODS_RECEIPT (
    GOODS_RECEIPT_NUMBER VARCHAR NOT NULL PRIMARY KEY,
    ORDER_NUMBER VARCHAR NOT NULL,
    LINE_NUMBER VARCHAR NOT NULL,
    REVERSED_GOODS_RECEIPT_NUMBER VARCHAR,
    RECEIVING_DATE DATE,
    RECEIVED_QUANTITY NUMBER(18,3),
    RECEIVED_NET_SUM NUMBER(18,2),
    RECIPIENT VARCHAR,
    FOREIGN KEY (ORDER_NUMBER, LINE_NUMBER)
        REFERENCES PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE (ORDER_NUMBER, LINE_NUMBER),
    FOREIGN KEY (REVERSED_GOODS_RECEIPT_NUMBER)
        REFERENCES PURCHASE_ORDER_DB.CLEAN.PURCHASE_ORDER_LINE_GOODS_RECEIPT (GOODS_RECEIPT_NUMBER)
);

CREATE TABLE IF NOT EXISTS PURCHASE_ORDER_DB.BIZ.DIM_SUPPLIER (
